/* Poincare-disk {7,3} hyperbolic tiling — a constant-time slice of AdS_3.
   Geodesics are circles orthogonal to the boundary circle; the tiling is
   generated by repeated inversion in the seven sides of the central heptagon. */

(function () {
  "use strict";

  var canvas = document.getElementById("adsDisk");
  if (!canvas || !canvas.getContext) return;

  var P = 7, Q = 3, DEPTH = 4, MAX = 1600;

  function buildCircles() {
    var sp = Math.sin(Math.PI / P), cq = Math.cos(Math.PI / Q);
    var d2 = (cq * cq) / (cq * cq - sp * sp);
    var d = Math.sqrt(d2), r = Math.sqrt(d2 - 1);

    var seeds = [];
    for (var k = 0; k < P; k++) {
      var a = (2 * Math.PI * k) / P;
      seeds.push({ x: d * Math.cos(a), y: d * Math.sin(a), r: r });
    }

    var all = seeds.slice();
    var seen = Object.create(null);
    function key(c) {
      return c.x.toFixed(4) + "|" + c.y.toFixed(4) + "|" + c.r.toFixed(4);
    }
    all.forEach(function (c) { seen[key(c)] = 1; });

    var frontier = seeds.slice();
    for (var lvl = 0; lvl < DEPTH && all.length < MAX; lvl++) {
      var next = [];
      for (var i = 0; i < frontier.length && all.length < MAX; i++) {
        for (var j = 0; j < seeds.length; j++) {
          var m = seeds[j], c = frontier[i];
          var dx = c.x - m.x, dy = c.y - m.y;
          var den = dx * dx + dy * dy - c.r * c.r;
          if (Math.abs(den) < 1e-9) continue;
          var s = (m.r * m.r) / den;
          var nc = { x: m.x + s * dx, y: m.y + s * dy, r: Math.abs(s) * c.r };
          if (nc.r < 0.004 || !isFinite(nc.r)) continue;
          var kk = key(nc);
          if (seen[kk]) continue;
          seen[kk] = 1;
          all.push(nc);
          next.push(nc);
          if (all.length >= MAX) break;
        }
      }
      frontier = next;
      if (!frontier.length) break;
    }
    return all;
  }

  var circles = buildCircles();

  function draw() {
    var css = getComputedStyle(document.documentElement);
    var accent = css.getPropertyValue("--accent").trim() || "#8f1a26";
    var line = css.getPropertyValue("--line-strong").trim() || "#c3cbd6";
    var muted = css.getPropertyValue("--muted").trim() || "#6b7686";

    var box = canvas.getBoundingClientRect();
    var size = Math.max(160, Math.min(box.width || 320, 420));
    var dpr = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = Math.round(size * dpr);
    canvas.height = Math.round(size * dpr);

    var ctx = canvas.getContext("2d");
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, size, size);

    var pad = 3;
    var R = size / 2 - pad;
    var cx = size / 2, cy = size / 2;

    ctx.save();
    ctx.beginPath();
    ctx.arc(cx, cy, R, 0, 2 * Math.PI);
    ctx.clip();

    ctx.lineJoin = "round";
    for (var i = 0; i < circles.length; i++) {
      var c = circles[i];
      var pr = c.r * R;
      if (pr < 0.6) continue;
      // near the boundary the arcs crowd; fade them so the edge reads as a limit
      ctx.strokeStyle = i < P ? accent : line;
      ctx.globalAlpha = i < P ? 0.9 : Math.max(0.28, Math.min(0.85, pr / 45));
      ctx.lineWidth = i < P ? 1.15 : 0.75;
      ctx.beginPath();
      ctx.arc(cx + c.x * R, cy + c.y * R, pr, 0, 2 * Math.PI);
      ctx.stroke();
    }
    ctx.restore();

    ctx.globalAlpha = 1;
    ctx.strokeStyle = muted;
    ctx.lineWidth = 1.25;
    ctx.beginPath();
    ctx.arc(cx, cy, R, 0, 2 * Math.PI);
    ctx.stroke();
  }

  draw();

  var t;
  window.addEventListener("resize", function () {
    clearTimeout(t);
    t = setTimeout(draw, 150);
  });

  if (window.matchMedia) {
    var mq = window.matchMedia("(prefers-color-scheme: dark)");
    if (mq.addEventListener) mq.addEventListener("change", draw);
    else if (mq.addListener) mq.addListener(draw);
  }
})();
